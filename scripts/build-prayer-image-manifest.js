#!/usr/bin/env node
/**
 * Regenerates src/data/prayerImageManifest.json from the drop-in folders in
 * public/prayers/<PRAYER_ID>/. Runs automatically via the npm prestart/prebuild
 * hooks — you never need to run this by hand. Edit folders, not the manifest.
 *
 * See public/prayers/README.txt (also generated here) for the conventions.
 */
const fs = require('fs');
const path = require('path');
const { scanPrayerFolders } = require('./prayerFolderScan');

const root = path.join(__dirname, '..');
const prayersDir = path.join(root, 'public', 'prayers');
const outFile = path.join(root, 'src', 'data', 'prayerImageManifest.json');

fs.mkdirSync(prayersDir, { recursive: true });
const prayers = scanPrayerFolders(prayersDir);

const manifest = {
  generatedAt: new Date().toISOString(),
  note: 'Auto-generated from public/prayers/ folders — do not edit by hand; npm start/build rescans.',
  prayers,
};
fs.writeFileSync(outFile, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

const readme = `CARPETA DE IMÁGENES DE REZOS — PRAYER IMAGE FOLDERS
=====================================================

Crea una carpeta por rezo usando su ID y arrastra imágenes dentro
(Desde el Explorador de Windows, descargas, o copias de otras carpetas del repo).

Create one folder per prayer using its ID and drag images into it
(Windows Explorer, downloads, or copies from other repo folders).

Ejemplos / Examples:
  public/prayers/A/rosa.jpg          → imagen del Ave María
  public/prayers/A/03-dolorosa.jpg   → versículo 3 del Ave María (NN- = verso NN)
  public/prayers/MG1/cruz.jpg        → Misterio Gozoso 1
  public/prayers/LL/05-regina.jpg    → verso 5 de la Letanía

Reglas / Rules:
  - El primer archivo (orden alfabético) es la imagen fija del rezo.
    The alphabetically first file is the prayer's pinned image.
  - "NN-nombre.jpg" fija el verso NN (1-based) en rezos por verso.
    "NN-name.jpg" pins verse NN (1-based) for per-verse prayers.
  - COPIA las imágenes existentes del repo, no las muevas: otros rezos
    las referencian. / COPY existing repo images, never move them.
  - Carpeta vacía o inexistente = comportamiento actual (pool automático).
    Empty or missing folder = today's behavior (auto pool).
  - Ejecuta npm start / npm build y el manifiesto se regenera solo.
    npm start / npm build regenerates the manifest automatically.

IDs de rezos: scripts/prayer-folder-coverage.json (npm test genera la lista).
Prayer IDs list: generated by npm test into scripts/prayer-folder-coverage.json.
`;

fs.writeFileSync(path.join(prayersDir, 'README.txt'), readme, 'utf8');

const count = Object.keys(prayers).length;
console.log(`[prayer-image-manifest] ${count} prayer folder(s) → src/data/prayerImageManifest.json`);
